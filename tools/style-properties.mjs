/**
 * Which half of the stylesheet owns a given CSS property.
 *
 * This is the base/theme boundary, written once so the guard in
 * `check-style-layers.mjs` cannot drift from the rule a human is told to apply:
 *
 *   base/           structure and behaviour — what breaks the component if removed
 *   themes/<name>/  colour, sizing, spacing and typography — what only changes how it looks
 *
 * The partition is by *property name*, never by how a value looks. "Is `14px` a
 * size or a layout constant?" is a judgement call and judgement calls rot; "is
 * `font-size` typography?" is not. Grid *track definitions* stay in base for the
 * same reason — `grid-template-columns` describes the structure even though it
 * carries lengths, and a theme that disagrees overrides it from `doc.theme`.
 *
 * A property missing from both sets is reported rather than guessed at.
 */

