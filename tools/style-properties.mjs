/** A custom property assignment is a token value, which is always the theme's. */
const isCustomProperty = (property) => property.startsWith('--');

export function classify(property) {
  if (isCustomProperty(property)) return 'theme';
  if (BASE_PROPERTIES.has(property)) return 'base';
  if (THEME_PROPERTIES.has(property)) return 'theme';
  return 'unknown';
}
