/**
 * MUST (§13.3): CI fails if a new component lands without being added to the
 * kitchen sink.
 *
 * why this guard rather than a review checklist: the fixture is simultaneously
 * the golden-file target, the manual QA page, the print check and the example in
 * REFERENCE.md. A component missing from it is a component with no visual
 * regression coverage, and nobody notices until a preset breaks it.
 */

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import {
  CODE_LANGUAGES,
  PRESET_AXES,
  TAG_NAMES,
  TAGS,
  type TagSpec,
} from '../../src/core/contract.js';

const FIXTURE = readFileSync(
  fileURLToPath(new URL('../fixtures/kitchen-sink.html', import.meta.url)),
  'utf8',
);

/** `doc-toc` is generated by the runtime; writing it by hand is a build error. */
const GENERATED = TAG_NAMES.filter((name) => (TAGS[name] as TagSpec).generated === true);

describe('kitchen sink coverage', () => {
  for (const tagName of TAG_NAMES) {
    if (GENERATED.includes(tagName)) continue;

    it(`uses <${tagName}>`, () => {
      expect(
        FIXTURE.includes(`<${tagName}`),
        `Add <${tagName}> to tests/fixtures/kitchen-sink.html — §13.3 requires every component to appear there.`,
      ).toBe(true);
    });
  }

  it('does not hand-write the generated tag', () => {
    for (const tagName of GENERATED) {
      expect(FIXTURE.includes(`<${tagName}`)).toBe(false);
    }
  });

  it('exercises every value of every enumerated attribute', () => {
    const missing: string[] = [];

    for (const tagName of TAG_NAMES) {
      const spec = TAGS[tagName] as TagSpec;
      for (const [attribute, definition] of Object.entries(spec.attributes)) {
        if (definition.kind.type !== 'enum') continue;
        // A document has exactly one doc-page, so it can carry exactly one value
        // per preset axis. `tests/components/presets.test.ts` covers the rest by
        // swapping the attributes at runtime.
        if (tagName === 'doc-page') continue;
        // Code languages get their own assertion below; requiring all seventeen
        // in one fixture would bury the rest of the document.
        if (attribute === 'lang') continue;

        for (const value of definition.kind.values) {
          if (FIXTURE.includes(`${attribute}="${value}"`)) continue;
          missing.push(`${tagName}[${attribute}="${value}"]`);
        }
      }
    }

    expect(missing, `Not exercised in the kitchen sink: ${missing.join(', ')}`).toEqual([]);
  });

  it('names every preset axis on the root, so a screenshot pins the defaults', () => {
    for (const axis of Object.keys(PRESET_AXES)) {
      expect(FIXTURE).toContain(`${axis}="`);
    }
  });

  it('keeps the code language allowlist honest', () => {
    // At least a representative spread; the full list lives in contract.ts and
    // is asserted by the highlighter's own test.
    expect(CODE_LANGUAGES).toContain('ts');
    expect(CODE_LANGUAGES).toContain('text');
    for (const language of ['ts', 'bash', 'css', 'json', 'text']) {
      expect(FIXTURE).toContain(`lang="${language}"`);
    }
  });
});
